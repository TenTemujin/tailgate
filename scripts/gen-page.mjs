// Embeds src/page.html as a TS string so tsx, tsc and `bun build --compile` all see it.
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync('src/page.html', 'utf8');
writeFileSync('src/page.gen.ts', `// Generated by scripts/gen-page.mjs from src/page.html. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
